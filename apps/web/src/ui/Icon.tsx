/** One icon with its label as aria-label and tooltip; `label` overrides it ("Answer" -> "Your answer"). */
export function Icon({
  name,
  label,
  size = 16,
  ...rest
}: { name: IconName; label?: string; size?: number } & Omit<SVGProps<SVGSVGElement>, 'ref'>) {
  const Glyph = GLYPHS[ICON_SPEC[name][0]];
  const text = ICON_SPEC[name][1];
  if (rest['aria-hidden']) return <Glyph width={size} height={size} data-icon={name} {...rest} />;
  const l = label ?? text;
  return (
    <Glyph width={size} height={size} role="img" aria-label={l} data-icon={name} {...rest}>
      <title>{l}</title>
    </Glyph>
  );
}
