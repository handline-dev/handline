import { writeFileSync } from 'node:fs';
const [,, out, url, mode] = process.argv;
const list = await (await fetch('http://127.0.0.1:9333/json/new?about:blank', { method: 'PUT' })).json();
const ws = new WebSocket(list.webSocketDebuggerUrl);
await new Promise((r) => (ws.onopen = r));
let id = 0; const pend = new Map();
ws.onmessage = (m) => { const d = JSON.parse(m.data); pend.get(d.id)?.(d.result); };
const send = (method, params = {}) => new Promise((r) => { const i = ++id; pend.set(i, r); ws.send(JSON.stringify({ id: i, method, params })); });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const ev = (expression) => send('Runtime.evaluate', { expression, awaitPromise: true });
const shot = async (name) => writeFileSync(out.replace('.png', name + '.png'), Buffer.from((await send('Page.captureScreenshot', { format: 'png' })).data, 'base64'));
await send('Emulation.setDeviceMetricsOverride', { width: 1500, height: 900, deviceScaleFactor: 2, mobile: false });
await send('Page.navigate', { url });
await sleep(4000);
await ev(`document.querySelector('button[aria-label="Add a tab"]').click()`); await sleep(400);
await ev(`[...document.querySelectorAll('[role=menuitem]')].find(b=>b.textContent.includes('Tasks')).click()`); await sleep(1500);
await shot('-list');
await ev(`document.querySelector('.tasks-tab-row')?.parentElement.querySelector('button[aria-label="Actions"]')?.click()`); await sleep(600);
await shot('-menu');
await ev(`document.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}))`); await sleep(300);
await ev(`document.querySelector('button[aria-label="Select tasks"]')?.click()`); await sleep(500);
await shot('-select');
ws.close();
