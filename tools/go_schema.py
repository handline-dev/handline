#!/usr/bin/env python3
"""Write the Go daemon's migrations (go/internal/store/migrations/) from handline/db/schema.py MIGRATIONS:

    python3 tools/go_schema.py          write them
    python3 tools/go_schema.py --check  exit 1 if what is committed is stale (tests/infra/test_go_schema.py runs this)

Each Python step is run in order on an empty database and what it added is dumped as SQL: new tables, indexes and
triggers, and new `cursors` rows. A step that changes an object it did not create, or writes other data, cannot be
dumped this way and stops the generator: that step is ported by hand into the Go store and this script told so.
manifest.json lists (version, name, additive) for the Go store, which learns its steps from it alone."""
import json
import sqlite3
import sys
import tempfile
from pathlib import Path

root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(root))
from handline.db import schema  # noqa: E402

OUT = root / "go" / "internal" / "store" / "migrations"


def strip_comments(sql: str) -> str:
    """Drop `--` comments (outside quotes) and the blank lines they leave: the explanations stay in schema.py,
    and its task and chat ids are not carried into this repo's new files."""
    lines = []
    for line in sql.splitlines():
        quote = None
        for i, ch in enumerate(line):
            if quote:
                quote = None if ch == quote else quote
            elif ch in "'\"":
                quote = ch
            elif line.startswith("--", i):
                line = line[:i]
                break
        if line.strip():
            lines.append(line.rstrip())
    return "\n".join(lines)


def _objects(con) -> dict:
    return {(t, n): sql for t, n, sql in con.execute(
        "SELECT type, name, sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY rowid")}


def _marks(con) -> dict:
    try:
        return dict(con.execute("SELECT name, row_id FROM cursors"))
    except sqlite3.OperationalError:
        return {}


def render() -> dict[str, str]:
    """File name -> text for every generated file."""
    files = {}
    steps = []
    with tempfile.TemporaryDirectory() as tmp:
        con = sqlite3.connect(Path(tmp) / "steps.sqlite", isolation_level=None)
        before, marks_before = {}, {}
        for version, name, step, additive in schema.MIGRATIONS:
            step(con)
            after, marks_after = _objects(con), _marks(con)
            changed = [k for k in before if after.get(k) != before[k]]
            if changed:
                sys.exit(f"go_schema: step {version} ({name}) changes {changed}, which it did not create; "
                         f"port it into the Go store by hand and teach this script")
            order = {"table": 0, "index": 1}
            new = sorted((k for k in after if k not in before), key=lambda k: order.get(k[0], 2))
            body = [f"-- Generated by tools/go_schema.py from handline/db/schema.py step {version} ({name}); do not edit."]
            body += [strip_comments(after[k]).rstrip(";") + ";" for k in new]
            body += [f"INSERT INTO cursors(name, row_id, updated) VALUES('{n}', {r}, CAST(strftime('%s','now') AS INTEGER));"
                     for n, r in sorted(marks_after.items()) if marks_before.get(n) != r]
            files[f"{version:04d}_{name}.sql"] = "\n".join(body) + "\n"
            steps.append({"version": version, "name": name, "additive": bool(additive)})
            before, marks_before = after, marks_after
    files["manifest.json"] = json.dumps(steps, indent=1) + "\n"
    return files


def main(argv: list[str]) -> int:
    files = render()
    if "--check" in argv:
        have = {p.name: p.read_text() for p in OUT.iterdir()} if OUT.is_dir() else {}
        stale = sorted(n for n in files if have.get(n) != files[n]) + sorted(n for n in have if n not in files)
        if stale:
            print(f"go_schema: stale: {', '.join(stale)}; run python3 tools/go_schema.py", file=sys.stderr)
            return 1
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for p in OUT.iterdir():
        if p.name not in files:
            p.unlink()
    for name, text in files.items():
        (OUT / name).write_text(text)
    print(OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
