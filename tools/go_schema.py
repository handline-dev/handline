#!/usr/bin/env python3
"""Write the Go daemon's baseline migration (go/internal/store/migrations/0001_baseline.sql) by running
handline/db/schema.py's baseline on an empty database and dumping what it made: the baseline adds columns and
indexes after SCHEMA, so SCHEMA alone is not the schema. Run it when the baseline changes; the Go store test
compares a fresh Go database with a fresh Python one and fails on a drift."""
import sqlite3
import sys
import tempfile
from pathlib import Path

root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(root))
from handline.db import schema  # noqa: E402

with tempfile.TemporaryDirectory() as tmp:
    con = sqlite3.connect(Path(tmp) / "baseline.sqlite", isolation_level=None)
    schema._baseline(con)
    objects = con.execute("SELECT sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' "
                          "ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 ELSE 2 END, rowid").fetchall()
    marks = con.execute("SELECT name, row_id FROM cursors ORDER BY name").fetchall()



def strip_comments(sql: str) -> str:
    """Drop `--` comments (outside quotes) and the blank lines they leave: the explanations stay in schema.py,
    and its task and chat ids are not carried into this repo's new files."""
    lines = []
    for line in sql.splitlines():
        quote = None
        for i, ch in enumerate(line):
            if quote:
                quote = None if ch == quote else quote
            elif ch in "'\"":
                quote = ch
            elif line.startswith("--", i):
                line = line[:i]
                break
        if line.strip():
            lines.append(line.rstrip())
    return "\n".join(lines)


out = root / "go" / "internal" / "store" / "migrations" / "0001_baseline.sql"
lines = ["-- Generated by tools/go_schema.py from handline/db/schema.py's baseline on an empty database; do not edit."]
lines += [strip_comments(sql).rstrip(";") + ";" for (sql,) in objects]
lines += [f"INSERT INTO cursors(name, row_id, updated) VALUES('{name}', {row_id}, CAST(strftime('%s','now') AS INTEGER));"
          for name, row_id in marks]
out.write_text("\n".join(lines) + "\n")
print(out)
